export const browserMessages = defineRendererMessageBundle({
  namespace: 'feature.browser',
  fallbackLocale: 'zh-CN',
  messages: {
    'zh-CN': browserZhCN,
    'en-US': browserEnUS,
  },
});

export function translateBrowserMessage(
  locale: 'zh-CN' | 'en-US',
  key: BrowserMessageKey,
): string {
  return locale === 'en-US' ? browserEnUS[key] : browserZhCN[key];
}
