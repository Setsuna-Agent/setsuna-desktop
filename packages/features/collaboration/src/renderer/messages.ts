function builtinRoleMessages(language: RuntimeInterfaceLanguage): Record<`feature.collaboration.roles.${string}`, string> {
  return Object.fromEntries(BUILTIN_COLLABORATION_ROLES.flatMap((name) => {
    const text = builtinCollaborationRoleText(name, language)!;
    return [
      [`feature.collaboration.roles.${name}.description`, text.description],
      [`feature.collaboration.roles.${name}.instructions`, text.instructions],
    ];
  }));
}

