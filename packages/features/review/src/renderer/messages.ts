export const reviewMessages = defineRendererMessageBundle({
  namespace: 'feature.review',
  fallbackLocale: 'zh-CN',
  messages: {
    'zh-CN': reviewZhCN,
    'en-US': reviewEnUS,
  },
});

export function translateReviewMessage(
  locale: 'zh-CN' | 'en-US',
  key: ReviewMessageKey,
  params?: Record<string, string | number>,
): string {
  const template = locale === 'en-US' ? reviewEnUS[key] : reviewZhCN[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/gu, (match, name: string) => String(params[name] ?? match));
}
