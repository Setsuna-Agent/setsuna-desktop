import * as lucide from 'lucide-react';

const require = createRequire(import.meta.url);
const packageRoot = path.dirname(require.resolve('lucide-react/package.json'));
const license = await readFile(path.join(packageRoot, 'LICENSE'), 'utf8');
const { version } = JSON.parse(await readFile(path.join(packageRoot, 'package.json'), 'utf8'));
const names = [
  'Plus', 'Minus', 'X', 'Check', 'CheckCheck', 'Search', 'Filter', 'ArrowUpDown',
  'ChevronDown', 'ChevronUp', 'ChevronLeft', 'ChevronRight', 'ArrowLeft', 'ArrowRight', 'ArrowUpRight',
  'MoreHorizontal', 'MoreVertical', 'Pencil', 'Trash2', 'Copy', 'Clipboard', 'Save',
  'Download', 'Upload', 'RefreshCw', 'RotateCcw', 'Settings', 'SlidersHorizontal', 'ExternalLink', 'Link',
  'Home', 'LayoutDashboard', 'PanelsTopLeft', 'Table2', 'Columns3', 'Rows3', 'List', 'ListChecks',
  'ChartColumn', 'ChartLine', 'ChartPie', 'File', 'FileText', 'FileSpreadsheet', 'Folder', 'FolderOpen',
  'Calendar', 'Clock', 'User', 'Users', 'Mail', 'Phone', 'MapPin', 'Globe', 'Tag', 'Bookmark',
  'Star', 'Heart', 'Bell', 'Info', 'CircleHelp', 'CircleCheck', 'TriangleAlert', 'LoaderCircle',
  'Eye', 'EyeOff', 'Lock', 'Unlock', 'Play', 'Square', 'Send', 'MessageSquare', 'MessagesSquare',
  'PanelLeft', 'GripVertical', 'Database', 'Sparkles', 'Laptop', 'Sun', 'Moon',
];
const icons = Object.fromEntries(names.map((name) => {
  if (!lucide[name]) throw new Error(`Unknown Lucide export: ${name}`);
  const svg = renderToStaticMarkup(createElement(lucide[name]));
  const content = /^<svg\b[^>]*>([\s\S]*)<\/svg>$/u.exec(svg)?.[1];
  if (!content) throw new Error(`Unexpected SVG source: ${name}`);
  const id = name.replace(/([a-z0-9])([A-Z])/gu, '$1-$2').replace(/([a-z])(\d+)/gu, '$1-$2').toLowerCase();
  return [id, content];
}));

// Serialize this small DOM adapter with the SVG data; generated apps need no React runtime.
function installIcons(window, icons) {
  const document = window.document;
  const namespace = 'http://www.w3.org/2000/svg';
  const names = Object.freeze(Object.keys(icons));
  const create = (name, { size = 16, label } = {}) => {
    if (!Object.hasOwn(icons, name)) throw new Error(`Unknown Setsuna icon: ${name}`);
    const svg = document.createElementNS(namespace, 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('class', 'sa-icon');
    svg.setAttribute('fill', 'none');
    svg.setAttribute('stroke', 'currentColor');
    svg.setAttribute('stroke-width', '1.75');
    svg.setAttribute('stroke-linecap', 'round');
    svg.setAttribute('stroke-linejoin', 'round');
    svg.setAttribute('focusable', 'false');
    svg.style.width = `${size}px`;
    svg.style.height = `${size}px`;
    // Only bundled SVG paths enter innerHTML. Caller-provided labels remain plain text.
    svg.innerHTML = icons[name];
    if (label) {
      svg.setAttribute('role', 'img');
      svg.setAttribute('aria-label', label);
    } else svg.setAttribute('aria-hidden', 'true');
    return svg;
  };
  const mount = (root = document) => {
    for (const target of root.querySelectorAll('[data-sa-icon]')) {
      target.replaceChildren(create(target.dataset.saIcon));
    }
  };
  window.SetsunaIcons = Object.freeze({ names, create, mount });
}

const output = `/* Generated by pnpm generate:app-icons from lucide-react ${version}. Do not edit.\n${license}*/\n/* global window */\n(${installIcons.toString()})(window, ${JSON.stringify(icons, null, 2)});\n`;
const destination = new URL('../plugins/app-builder/skills/create-plugin-in-chat/assets/ui-icons.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('App icons are outdated. Run pnpm generate:app-icons.');
} else await writeFile(destination, output);
console.log(`App Builder: ${names.length} offline Lucide icons ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
